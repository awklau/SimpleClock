"""Compile the supplied parameter specification to a checked-in C header.

The target never parses JSON. --check is a host/CI consistency check; changing
the specification requires regenerating the header and rebuilding the image.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "default_parameters.json"
OUTPUT = ROOT / "core/include/simpleclock/hybrid_defaults.h"


def generated():
    raw = SOURCE.read_bytes()
    spec = json.loads(raw)
    lines = [
        "/* SPDX-License-Identifier: MIT */",
        "/* clang-format off */",
        "/* Generated by tools/generate-hybrid-defaults.py; edit the JSON specification. */",
        "#ifndef SIMPLECLOCK_HYBRID_DEFAULTS_H",
        "#define SIMPLECLOCK_HYBRID_DEFAULTS_H",
        '#define SC_HYBRID_CONFIG_SHA256 "' + hashlib.sha256(raw).hexdigest() + '"',
    ]
    for section, entries in spec.items():
        if not isinstance(entries, dict):
            entries = {section: entries}
            section = ""
        for key, value in entries.items():
            name = "SC_HYBRID_" + (section + "_" if section else "") + key
            if isinstance(value, bool):
                text = "1" if value else "0"
            elif isinstance(value, str):
                text = json.dumps(value)
            else:
                text = str(value)
            lines.append(f"#define {name.upper()} {text}")
    return "\n".join(lines + ["#endif", "/* clang-format on */", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generated()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit(
                "Hybrid defaults differ from specification; regenerate before building"
            )
        print("Hybrid compiled defaults match default_parameters.json")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")
